#!/usr/bin/env python3
"""Writes docs/RIVER_GAPS.md: what each river has and lacks. Run after any data change: python3 scripts/rivers/gaps.py"""
import json, os, glob

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
rivers = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'data/rivers/*.json'))):
    rivers[os.path.basename(f)[:-5]] = json.load(open(f))


def has(p):
    return os.path.exists(os.path.join(ROOT, p))


def n(x):
    return len(x) if x else 0


def checks(rid, r):
    s = r.get('stats') or {}
    fl = s.get('flow') or {}
    c = {}
    c['Reach & coords'] = bool(r.get('reach') and r.get('coords'))
    c['Access points'] = n(r.get('access')) >= 2
    c['Camps'] = n(r.get('camps')) > 0
    c['Rapids'] = n(r.get('rapids')) > 0
    c['Hikes'] = n(r.get('hikes')) > 0
    c['Geology'] = n(r.get('geology')) > 0
    c['Almanac'] = bool(r.get('almanac'))
    c['Permit & rules'] = bool(r.get('permit')) and n(r.get('rules')) > 0
    c['Class & season'] = bool(s.get('class') and s.get('season'))
    c['Elevation & gradient'] = bool(s.get('elev') and s.get('gradient') is not None)
    c['Recommended flow'] = fl.get('min') is not None or fl.get('max') is not None
    c['Flow bands'] = n(s.get('bands')) > 0
    c['Gauges to watch'] = any(g.get('id') for g in s.get('gauges', []))
    c['Typical flow by date'] = 'flowDoy' in r
    c['Typical weather by date'] = 'climateDoy' in r
    c['Map line'] = has(f'data/geo/nhd/{rid}.json') or has(f'data/geo/{rid}.json')
    c['Camp horizons'] = has(f'data/geo/{rid}.json')
    c['Basin map'] = has(f'data/basin/{rid}.json')
    return c


rows = {rid: checks(rid, r) for rid, r in rivers.items()}
cols = list(next(iter(rows.values())))
out = ['# River gaps', '', 'Generated by `python3 scripts/rivers/gaps.py`. A dash is missing. Counts are the number of entries.', '']
out += ['## Known issues', '',
        '- **Rain row hidden.** The saved `rain` values count days with 0.01 in or more, which includes drizzle days and runs far above what a trip sees (Grand Canyon in January shows 26%). `weather.py` now counts 0.04 in (1 mm). Rerun every river with `python3 scripts/rivers/weather.py --force` (Open-Meteo limits requests per day), then restore the "Rain or snow" row in `Conditions` in `src/App.jsx`.',
        '- Open-Meteo returned "Daily API request limit exceeded" on 2026-10-16, so no weather could be added. Retry the 18 rivers without `climateDoy`.',
        '- Left blank on purpose: Tuolumne gauge (the only live gauge is above the run); flow bands, geology, and the 8 empty rivers need sourced content.',
        '- Weather for rivers marked "height at coordinates" may be taken on a ridge, not the river.', '']
out.append('## What is missing, by item')
out.append('')
for col in cols:
    miss = [rid for rid in rows if not rows[rid][col]]
    out.append(f'- **{col}** ({len(rows) - len(miss)} of {len(rows)} have it)' + (': missing for ' + ', '.join(miss) if miss else ''))
out.append('')
out.append('## What is missing, by river')
out.append('')
for rid, r in rivers.items():
    miss = [c for c in cols if not rows[rid][c]]
    cnt = f"{n(r.get('camps'))} camps, {n(r.get('rapids'))} rapids, {n(r.get('hikes'))} hikes"
    extra = ''
    cd = r.get('climateDoy')
    if cd and cd.get('elevFrom') == 'point':
        extra = ' Weather height is taken at the coordinates, not the river: check.'
    out.append(f"- **{r.get('name', rid)}** (`{rid}`; {cnt}): " + (', '.join(miss) if miss else 'complete') + '.' + extra)
out.append('')
open(os.path.join(ROOT, 'docs/RIVER_GAPS.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
